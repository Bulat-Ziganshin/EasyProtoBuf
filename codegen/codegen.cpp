// Is it a repeated Protobuf field?
bool is_repeated(const FieldDescriptorProto& field)
{
    return (field.label == FieldDescriptorProto::LABEL_REPEATED);
}


// Does this field have corresponding has_* flag?
bool hasfield_enabled(const FieldDescriptorProto& field,
                      const GenerationContext& context)
{
    return (! is_repeated(field)  &&  ! context.options.no_has_fields);
}


// The C++ member name of a field.
//
// A Protobuf field name is a valid C++ identifier in every case but one: a
// name that is a C++ keyword cannot be spelled verbatim, and the reference
// compiler escapes it - the accessor of a field named `class` is `class_`
// (compiler/cpp/helpers.cc:642-654). The member carries the same escaped
// name, so the field, its presence flag and the codec functions all speak
// one name.
std::string field_member_name(const FieldDescriptorProto& field)
{
    return easypb_codegen::cpp_identifier(view_text(field.name));
}


// The C++ spelling of one declaration name, refused with the declaration the
// caller is reading (U-30). `cpp_identifier` owns the rule; this wrapper only
// remembers where the name came from, so the diagnostic can carry a source
// position instead of `unknown_location`.
std::string cpp_identifier_at(const std::string& name,
                              const easypb_schema::DescriptorPath& path)
{
    try {
        return easypb_codegen::cpp_identifier(name);
    } catch (const std::exception& problem) {
        throw EmitterError(path, problem.what());
    }
}


// The member and presence-flag names of one field, positioned at that field.
std::string field_member_name_at(const FieldDescriptorProto& field,
                                 const easypb_schema::DescriptorPath& path)
{
    return cpp_identifier_at(view_text(field.name), path);
}


// The C++ member name of a field's presence flag.
//
// The flag is named after the field, so it is named after the ESCAPED field:
// a field named `class` owns the flag `has_class_`, which is how the
// reference compiler spells its presence accessor.
std::string field_flag_name(const FieldDescriptorProto& field)
{
    return "has_" + field_member_name(field);
}


std::string field_flag_name_at(const FieldDescriptorProto& field,
                               const easypb_schema::DescriptorPath& path)
{
    return "has_" + field_member_name_at(field, path);
}


// Is it a Protobuf numeric field (including enums/bools)?
bool is_numeric_field(const FieldDescriptorProto& field)
{
    return (field.type != FieldDescriptorProto::TYPE_STRING) &&
           (field.type != FieldDescriptorProto::TYPE_BYTES) &&
           (field.type != FieldDescriptorProto::TYPE_MESSAGE) &&
           (field.type != FieldDescriptorProto::TYPE_GROUP);
}


// Serialize this field in the more compact "packed" Protobuf wire format?
bool write_as_packed(const FieldDescriptorProto& field,
                     const GenerationContext& context)
{
    // The proto3 packed default comes from the classification made once per
    // invocation; no part of the generator compares `file.syntax` itself
    // (plan 5 A25), and an unsupported file never receives proto3 semantics.
    // The linker refuses FILE_SYNTAX_UNSUPPORTED before generation.
    //
    // U-04: the schema default is answered by `effective_packed`, the same
    // helper the descriptor merge compares, so the wire format cannot depend
    // on which container was named first.
    if (!is_repeated(field) || !is_numeric_field(field)) return false;
    if (context.options.packed) return true;
    if (context.options.no_packed) return false;
    return easypb_schema::effective_packed(field, context.syntax);
}


// PB type as used in .proto file (e.g. "fixed32")
//
// The two shapes the model has no spelling for - a group, and a kind outside
// the TYPE_* set - are REFUSED here instead of being answered with a
// sentinel. The semantics layer refuses both (DIAGNOSTIC_INVALID_FIELD_TYPE,
// plan 5 follow-up S1 W-10), so reaching this point means a path that
// bypassed that layer, and a header that said "???type" would be a silent
// lie: it compiles nowhere and means nothing. A loud failure is the better
// answer, and it is the same shape as the other emitter refusals in this
// file.
str_view pbtype_name(const FieldDescriptorProto& field)
{
    switch(field.type)
    {
        case FieldDescriptorProto::TYPE_DOUBLE:    return "double";
        case FieldDescriptorProto::TYPE_FLOAT:     return "float";
        case FieldDescriptorProto::TYPE_INT64:     return "int64";
        case FieldDescriptorProto::TYPE_UINT64:    return "uint64";
        case FieldDescriptorProto::TYPE_INT32:     return "int32";
        case FieldDescriptorProto::TYPE_FIXED64:   return "fixed64";
        case FieldDescriptorProto::TYPE_FIXED32:   return "fixed32";
        case FieldDescriptorProto::TYPE_BOOL:      return "bool";
        case FieldDescriptorProto::TYPE_STRING:    return "string";
        case FieldDescriptorProto::TYPE_GROUP:
            throw std::runtime_error(
                myformat("Field '{0}' is a group, and this generator does not "
                         "support group types",
                         field.name));
        case FieldDescriptorProto::TYPE_MESSAGE:   return "message";
        case FieldDescriptorProto::TYPE_BYTES:     return "bytes";
        case FieldDescriptorProto::TYPE_UINT32:    return "uint32";
        case FieldDescriptorProto::TYPE_ENUM:      return "enum";
        case FieldDescriptorProto::TYPE_SFIXED32:  return "sfixed32";
        case FieldDescriptorProto::TYPE_SFIXED64:  return "sfixed64";
        case FieldDescriptorProto::TYPE_SINT32:    return "sint32";
        case FieldDescriptorProto::TYPE_SINT64:    return "sint64";
    }

    throw std::runtime_error(
        myformat("Field '{0}' declares an unknown type (kind {1})",
                 field.name, number_to_string(field.type)));
}


// Return an absolute C++ spelling for a fully qualified Protobuf message/enum type.
// Keeping user-defined field types absolute makes the generated declaration
// independent of the package namespace and of any nearer C++ name.
std::string cpp_qualified_type_str(str_view message_type)
{
    return easypb_codegen::cpp_absolute_name(message_type);
}


// Return C++ type corresponding to the base type (without "repeated") of the Protobuf field
std::string base_cpp_type_as_str(const FieldDescriptorProto& field,
                                 const GenerationContext& context)
{
    // According to https://github.com/protocolbuffers/protobuf/blob/c05b320d9c18173bfce36c4bef22f9953d340ff9/src/google/protobuf/descriptor.h#L780
    switch(field.type)
    {
        case FieldDescriptorProto::TYPE_INT32:
        case FieldDescriptorProto::TYPE_SINT32:
        case FieldDescriptorProto::TYPE_SFIXED32: return "::int32_t";

        case FieldDescriptorProto::TYPE_INT64:
        case FieldDescriptorProto::TYPE_SINT64:
        case FieldDescriptorProto::TYPE_SFIXED64: return "::int64_t";

        case FieldDescriptorProto::TYPE_UINT32:
        case FieldDescriptorProto::TYPE_FIXED32:  return "::uint32_t";

        case FieldDescriptorProto::TYPE_UINT64:
        case FieldDescriptorProto::TYPE_FIXED64:  return "::uint64_t";

        case FieldDescriptorProto::TYPE_DOUBLE:   return "double";

        case FieldDescriptorProto::TYPE_FLOAT:    return "float";

        case FieldDescriptorProto::TYPE_BOOL:     return "bool";

        case FieldDescriptorProto::TYPE_STRING:
        case FieldDescriptorProto::TYPE_BYTES:    return context.options.cpp_string_type;

        case FieldDescriptorProto::TYPE_ENUM:
        case FieldDescriptorProto::TYPE_MESSAGE:  return cpp_qualified_type_str(field.type_name);

        case FieldDescriptorProto::TYPE_GROUP:
            throw std::runtime_error(
                myformat("Field '{0}' is a group, and this generator does not "
                         "support group types",
                         field.name));
    }

    throw std::runtime_error(
        myformat("Field '{0}' declares an unknown type (kind {1})",
                 field.name, number_to_string(field.type)));
}


struct MapType
{
    const FieldDescriptorProto* key_field = nullptr;
    const FieldDescriptorProto* value_field = nullptr;
};

using MapTypeByName = std::map<std::string, MapType>;


// PB type suffix used by Encoder/Decoder methods (e.g. "fixed32" or "map_string_int32")
std::string protobuf_type_as_str(const FieldDescriptorProto& field, const MapType* map_type)
{
    if (map_type) {
        return myformat("map_{0}_{1}",
                        pbtype_name(*map_type->key_field),
                        pbtype_name(*map_type->value_field));
    }

    return std::string(pbtype_name(field));
}

// GCC 4.7 still tokenizes "<::" as the alternative token "<:" followed by ':',
// even in contexts where newer C++11 compilers correctly interpret it as '<' + '::'.
// Keep generated type spellings accepted by that compiler by separating the tokens.
std::string cpp_type_legacy_safe(std::string type)
{
    // The parameter is an owned buffer this call is free to rewrite, and the
    // caller's temporary was moved into it, so the replacement is done in
    // place: an earlier helper built a SECOND string and filled it with the
    // same bytes one character longer.
    const std::string find = "<::";
    std::size_t pos = type.find(find);
    while (pos != std::string::npos) {
        type.replace(pos, find.size(), "< ::");
        pos = type.find(find, pos + 4);
    }
    return type;
}


// Return C++ type for the Protobuf field
std::string cpp_type_as_str(const FieldDescriptorProto& field, const MapType* map_type,
                            const GenerationContext& context)
{
    const bool has_cpp_type =
        field.has_options && field.options.has_cpp && field.options.cpp.has_type;

    if (has_cpp_type && field.options.cpp.type.empty()) {
        throw std::runtime_error(
            myformat("EasyProtoBuf C++ type option for field '{0}' must not be empty",
                     field.name));
    }

    if (map_type) {
        return cpp_type_legacy_safe(
            myformat(has_cpp_type ? field.options.cpp.type : context.options.cpp_map_type,
                     base_cpp_type_as_str(*map_type->key_field, context),
                     base_cpp_type_as_str(*map_type->value_field, context)));
    }

    const std::string basetype_str = base_cpp_type_as_str(field, context);

    if (is_repeated(field)) {
        return cpp_type_legacy_safe(
            myformat(has_cpp_type ? field.options.cpp.type : context.options.cpp_repeated_type,
                     basetype_str));
    }

    return has_cpp_type ? cpp_type_legacy_safe(myformat(field.options.cpp.type, basetype_str))
                        : basetype_str;
}


// One declaration of one C++ scope.
//
// A C++ scope cannot hold two declarations with the same name: a struct
// cannot declare a member twice, and a scope cannot hold two types with one
// name. The Protobuf names of a scope are unique, but the C++ spelling is
// not: the escape rule (cpp_identifier) gives a keyword a suffix, and a
// second declaration may already own the suffixed name - `class` and
// `class_` both become `class_`.
//
// `kind` is what the declaration is, for the diagnostic and for the one
// asymmetry C++ has about a class's own name: a nested type or an enumerator
// that carries it is ill-formed ("'Outer::Outer' has the same name as the
// class in which it is declared"), while a non-static data member may carry it
// because only a user-declared constructor would make that ill-formed
// ([class.mem]/22) and a generated struct declares none.
enum ScopeMemberKind
{
    SCOPE_MEMBER_FIELD,
    SCOPE_MEMBER_PRESENCE_FLAG,
    SCOPE_MEMBER_TYPE,             // a nested or top-level message or enum
    SCOPE_MEMBER_ENUMERATOR,
    SCOPE_MEMBER_CODEC,
    SCOPE_MEMBER_ENCLOSING_TYPE,   // the struct's own name
    SCOPE_MEMBER_GLOBAL_NAME       // a runtime type or a preamble typedef
};

struct ScopeMember
{
    std::string cpp_name;      // the name the header spells
    std::string description;   // what the declaration is, for the diagnostic
    ScopeMemberKind kind;
    // The declaration the member came from, so a refusal can be positioned
    // (U-30). Empty for a synthesized member: a generated codec, a runtime
    // namespace or a preamble typedef has no source declaration.
    easypb_schema::DescriptorPath path;
};


// The description of a member in a diagnostic: "field 'x'", "nested enum
// 'x'", "presence flag of the field 'x'".
std::string member_description(const std::string& kind,
                               const std::string& name)
{
    return myformat("{0} '{1}'", kind, name);
}


// Would declaring both members in one C++ scope fail to compile?
//
// Only one pair is legal: the struct's own name next to a field or a presence
// flag of that name (see ScopeMemberKind). Every other pair is a
// redeclaration.
bool cpp_declarations_conflict(const ScopeMember& first,
                               const ScopeMember& second)
{
    if (first.kind == SCOPE_MEMBER_ENCLOSING_TYPE ||
        second.kind == SCOPE_MEMBER_ENCLOSING_TYPE) {
        const ScopeMemberKind other =
            first.kind == SCOPE_MEMBER_ENCLOSING_TYPE ? second.kind
                                                      : first.kind;
        return other == SCOPE_MEMBER_TYPE ||
               other == SCOPE_MEMBER_ENUMERATOR;
    }
    return true;
}


// Refuse a scope that would declare the same C++ name twice.
//
// The reference compiler escapes a keyword the same way (its ResolveKeyword
// appends "_", compiler/cpp/helpers.cc:509-514), so it has the same hole:
// two messages named `class` and `class_` become two `class_` classes and
// its header does not compile, and two enum values named `class` and
// `class_` make it refuse the schema outright ("Enum name class_ has the
// same name as class if you ignore case and strip out the enum name prefix",
// measured against protoc 30.1). This project refuses every shape: a
// diagnostic instead of a header that cannot mean what the schema says.
void refuse_duplicate_cpp_names(const std::vector<ScopeMember>& members,
                                const std::string& scope)
{
    std::map<std::string, ScopeMember> seen;
    for (std::size_t i = 0; i < members.size(); ++i) {
        const std::map<std::string, ScopeMember>::const_iterator found =
            seen.find(members[i].cpp_name);
        if (found != seen.end() &&
            cpp_declarations_conflict(found->second, members[i])) {
            // The collision belongs to the second declaration; a synthesized
            // member has no path, so the first one is the fallback. Either way
            // the diagnostic is positioned rather than `unknown_location`
            // (U-30).
            const easypb_schema::DescriptorPath& blamed =
                ! members[i].path.empty() ? members[i].path
                                          : found->second.path;
            // The presence flag keeps the wording session S2 established for
            // it: the diagnostic names the field and the flag it collides
            // with, which is more precise than the generic one.
            const bool first_is_flag =
                found->second.kind == SCOPE_MEMBER_PRESENCE_FLAG;
            const bool second_is_flag =
                members[i].kind == SCOPE_MEMBER_PRESENCE_FLAG;
            if (first_is_flag || second_is_flag) {
                const ScopeMember& flag = first_is_flag
                    ? found->second : members[i];
                const ScopeMember& other = first_is_flag
                    ? members[i] : found->second;
                throw EmitterError(
                    blamed,
                    myformat("The {0} of {1} collides with the {2}: both "
                             "members would be named '{3}'",
                             other.description, scope, flag.description,
                             members[i].cpp_name));
            }
            throw EmitterError(
                blamed,
                myformat("In {0}, the {1} and the {2} would both be named "
                         "'{3}' in C++",
                         scope, found->second.description,
                         members[i].description, members[i].cpp_name));
        }
        if (found == seen.end()) {
            seen.insert(std::make_pair(members[i].cpp_name, members[i]));
        }
    }
}


// The enumerators of one enum.
//
// An unscoped enum's enumerators are members of the enum's own scope, so
// two of them cannot carry the same C++ name.
void check_enum_value_names(const EnumDescriptorProto& enum_type,
                            const easypb_schema::DescriptorPath& enum_path)
{
    std::vector<ScopeMember> members;
    for (std::size_t i = 0; i < enum_type.value.size(); ++i) {
        const auto& value = enum_type.value[i];
        ScopeMember member;
        member.path = easypb_schema::enum_value_path(
            enum_path, static_cast<int>(i));
        member.cpp_name = cpp_identifier_at(view_text(value.name),
                                            member.path);
        member.description = member_description("enum value",
                                                view_text(value.name));
        member.kind = SCOPE_MEMBER_ENUMERATOR;
        members.push_back(member);
    }
    if (members.empty()) return;
    refuse_duplicate_cpp_names(members,
                               myformat("the enum '{0}'",
                                        view_text(enum_type.name)));
}


// Generate an unscoped C++ enum with a fixed int32_t representation.  The
// fixed underlying type lets an open proto3 enum retain any unknown int32 value.
//
// The enum's own name and the names of its values are escaped the way the
// reference compiler escapes them: the enum of a schema that declares
// `enum class` is `class_` (compiler/cpp/helpers.cc:461-469), and the
// enumerator of a value named `class` is `class_` (helpers.cc:681-683).
std::string generate_enum(const EnumDescriptorProto& enum_type,
                          const std::string& indent,
                          const easypb_schema::DescriptorPath& enum_path)
{
    const std::string enum_name =
        cpp_identifier_at(view_text(enum_type.name), enum_path);
    std::string result = myformat("{0}enum {1} : {2}\n{0}{\n",
                                  indent, enum_name, CPP_ENUM_BASE_TYPE);

    for (std::size_t i = 0; i < enum_type.value.size(); ++i) {
        const auto& value = enum_type.value[i];
        result += myformat("{0}    {1} = {2}{3}\n",
                           indent,
                           cpp_identifier_at(
                               view_text(value.name),
                               easypb_schema::enum_value_path(
                                   enum_path, static_cast<int>(i))),
                           number_to_string(value.number),
                           i + 1 < enum_type.value.size() ? "," : "");
    }

    result += myformat("{0}};\n\n", indent);
    return result;
}


// Encoder code for a single field
std::string generate_field_encoder(const FieldDescriptorProto& field, const MapType* map_type,
                                   const GenerationContext& context)
{
    // "x." belongs to the literal: as an argument it cost a temporary
    // std::string of the name plus a second one for the concatenation, once
    // per field, and both were discarded immediately.
    return myformat("    pb.put_{0}{1}({2}, x.{3});\n",
    /* 0 */ ! map_type && is_repeated(field)
                ? (write_as_packed(field, context)? "packed_" : "repeated_")
                : "",
    /* 1 */ protobuf_type_as_str(field, map_type),
    /* 2 */ number_to_string(field.number),
    /* 3 */ field_member_name(field));
}


// Decoder code for a single field
std::string generate_field_decoder(const FieldDescriptorProto& field, const MapType* map_type,
                                   const GenerationContext& context)
{
    // Same as the encoder: the receiver spelling comes from the literal
    // instead of two temporaries per field.
    return myformat("            case {0}: pb.get_{1}{2}(&x.{3}{4}); break;\n",
    /* 0 */ number_to_string(field.number),
    /* 1 */ ! map_type && is_repeated(field)? "repeated_" : "",
    /* 2 */ protobuf_type_as_str(field, map_type),
    /* 3 */ field_member_name(field),
    /* 4 */ hasfield_enabled(field, context)
                ? myformat(", &x.{0}", field_flag_name(field))
                : "");
}


// The bytes a string or bytes default holds.
//
// A string default is stored DECODED: the reference compiler keeps the raw
// bytes in `default_value` (descriptor.cc:6738-6741), so a quote, a
// backslash, a newline and a NUL are all raw bytes there, and this project's
// own parser stores the same thing (proto_parser.cpp:1165-1169). A bytes
// default is stored C-ESCAPED: the reference compiler applies
// `absl::CUnescape` to it while it builds the field
// (descriptor.cc:6729-6732), and this project's parser writes the escaped
// spelling (proto_parser.cpp:1170-1174). The two kinds therefore need
// different treatment, and the decoder that owns the bytes spelling lives
// beside the grammar that validates it (easypb_schema::decode_bytes_escape).
std::string default_bytes(const FieldDescriptorProto& field)
{
    if (field.default_value.empty()) return std::string();
    const std::string stored = view_text(field.default_value);
    if (field.type != FieldDescriptorProto::TYPE_BYTES) {
        return stored;
    }
    std::string decoded;
    if (!easypb_schema::decode_bytes_escape(stored, decoded)) {
        throw std::runtime_error(
            myformat("Field '{0}' carries a bytes default the escape grammar "
                     "does not accept",
                     field.name));
    }
    return decoded;
}


// The C++ spelling of a byte string.
//
// The rules are the ones a C++ string literal needs and no more:
//
//   "  -> \"      \  -> \\      '  -> \'
//   LF -> \n     CR -> \r     TAB -> \t
//   every byte < 0x20 or >= 0x7F -> \ooo, ALWAYS three octal digits.
//
// The three digits are not a style choice: a hex escape would swallow the
// character behind it (C reads \x41B as one out-of-range hex escape) and a
// two-digit octal escape would swallow a digit behind it.
//
// A '?' is escaped when the byte BEFORE it is a '?', never when the byte
// after it is: a trigraph is "??X", so the second '?' of the pair is the one
// that has to be broken, and breaking it breaks every trigraph at once. The
// project builds with -std=c++11 (CMAKE_CXX_EXTENSIONS OFF), and GCC's ISO
// mode still has trigraphs: a trigraph is replaced in translation phase 1,
// BEFORE the backslash escape is read, so "\??" would still be "??=" after
// the replacement.
std::string canonical_cpp_literal(const std::string& bytes)
{
    std::string literal;
    literal.reserve(bytes.size() + 2);
    literal.push_back('"');
    for (std::size_t i = 0; i < bytes.size(); ++i) {
        const unsigned char c = static_cast<unsigned char>(bytes[i]);
        switch (c) {
            case '"':  literal.append("\\\""); break;
            case '\\': literal.append("\\\\"); break;
            case '\'': literal.append("\\'"); break;
            case '\n': literal.append("\\n"); break;
            case '\r': literal.append("\\r"); break;
            case '\t': literal.append("\\t"); break;
            case '?':
                if (i > 0 && bytes[i - 1] == '?') {
                    literal.append("\\?");
                } else {
                    literal.push_back('?');
                }
                break;
            default:
                if (c >= 32u && c < 127u) {
                    literal.push_back(static_cast<char>(c));
                } else {
                    literal.push_back('\\');
                    literal.push_back(static_cast<char>('0' + ((c >> 6) & 7u)));
                    literal.push_back(static_cast<char>('0' + ((c >> 3) & 7u)));
                    literal.push_back(static_cast<char>('0' + (c & 7u)));
                }
                break;
        }
    }
    literal.push_back('"');
    return literal;
}


// The C++ type a string or bytes field is generated with: the configured
// one, unless the field carries its own `(easypb.cpp).type` override.
std::string effective_string_type(const FieldDescriptorProto& field,
                                  const GenerationContext& context)
{
    if (field.has_options && field.options.has_cpp &&
        field.options.cpp.has_type && ! field.options.cpp.type.empty()) {
        return view_text(field.options.cpp.type);
    }
    return context.options.cpp_string_type;
}


// The initializer of a string or bytes member.
//
// A value with an embedded NUL cannot travel in a C++ string literal:
// std::string(const char*) stops at the NUL, so the value would be cut
// short. The two-argument form - std::string(literal, length) - is the only
// way to hand a length to the string, and it is used ONLY for such a value,
// so every other header keeps its current bytes.
//
// The braces are not a style choice. A non-static data member accepts only a
// brace-or-equal initializer ([class.mem]), so the parenthesized form
// `("a\000b", 3)` is not a member initializer at all: the parser reads it as
// a function declaration - the most vexing parse - and answers "expected
// identifier before string constant". The brace form is a direct
// initialization, which is what the length needs, and it is accepted by
// every toolchain this project supports (GCC 4.7 and Clang 3.1/3.3 among
// them).
//
// The length is the number of DECODED bytes, not the number of characters
// in the literal.
std::string string_default_str(const FieldDescriptorProto& field,
                                const GenerationContext& context)
{
    const std::string bytes = default_bytes(field);
    const std::string literal = canonical_cpp_literal(bytes);
    if (bytes.find('\0') == std::string::npos) {
        return myformat(" = {0}", literal);
    }
    // Only std::string can be built from a literal and a length, so a
    // different string type cannot carry this value at all. The refusal is
    // the owner's decision of 2026-10-21: a header that cannot mean what the
    // schema says is worse than a diagnostic.
    std::string type = effective_string_type(field, context);
    if (type.compare(0, 2, "::") == 0) type = type.substr(2);
    if (type != "std::string") {
        throw std::runtime_error(
            myformat("Field '{0}' has a default value with an embedded NUL, "
                     "which needs the two-argument std::string form; the "
                     "string type '{1}' cannot carry it",
                     field.name, type));
    }
    return "{" + literal + ", " +
           number_to_string(static_cast<int32_t>(bytes.size())) + "}";
}


// The initializer of a float or double member.
//
// The reference compiler resolves exactly three spellings of a
// floating-point default (descriptor.cc:6698-6712): "inf", "-inf" and "nan".
// They are not C++ identifiers, so the emitter spells them the way the
// reference compiler's own generated code does.
//
// Everything this function reads is canonical: the source parser and the
// descriptor adapter both store `canonical_float_default`'s output, so a
// spelling that survived them (a hand-built schema, or a future layer that
// bypassed the adapter) is refused here rather than reinterpreted. The
// refusal is defence in depth, not a user-facing path: `validate_default`
// already rejects the same text with a positioned diagnostic (CR-02, R1).
std::string float_default_str(const FieldDescriptorProto& field)
{
    if (field.default_value.empty()) return "";
    const std::string text = view_text(field.default_value);

    if (!easypb_schema::is_canonical_float_default(
            text, field.type == FieldDescriptorProto::TYPE_FLOAT)) {
        throw std::runtime_error(
            myformat("Field '{0}' carries the non-canonical floating-point "
                     "default '{1}'", field.name, text));
    }

    const std::string limits =
        field.type == FieldDescriptorProto::TYPE_FLOAT ? "float" : "double";
    if (text == "inf") {
        return myformat(" = ::std::numeric_limits<{0}>::infinity()", limits);
    }
    if (text == "-inf") {
        return myformat(" = -::std::numeric_limits<{0}>::infinity()", limits);
    }
    if (text == "nan") {
        return myformat(" = ::std::numeric_limits<{0}>::quiet_NaN()", limits);
    }
    // W-04: the canonical text for negative zero is "-0", but the C++ token
    // `-0` is an integer zero and would initialize a floating member as +0.0.
    if (text == "-0") return " = -0.0";
    return myformat(" = {0}", text);
}


// The initializer of an integral member.
//
// Both frontends store the canonical decimal spelling, so the text is read
// again only to decide how C++ can spell it. A 64-bit extreme needs a typed
// literal: `-9223372036854775808` and `18446744073709551615` are
// unsuffixed-decimal forms that C++11 calls ill-formed, even though GCC
// accepts them without `-pedantic-errors` (CR-05). Every other integral value
// fits `long long` as an unsuffixed decimal, so it keeps the historical
// spelling. A non-canonical text is refused here for the same reason the
// float emitter refuses one: the emitter must not become a third interpreter
// of the literal (R1).
std::string integral_default_str(const FieldDescriptorProto& field)
{
    const std::string text = view_text(field.default_value);
    std::string canonical;
    if (!easypb_schema::canonical_integral_default(text, canonical) ||
        canonical != text) {
        throw std::runtime_error(
            myformat("Field '{0}' carries the non-canonical integral default "
                     "'{1}'", field.name, text));
    }

    bool negative = false;
    std::uint64_t magnitude = 0;
    (void)easypb_schema::parse_integral_default_literal(text, negative,
                                                        magnitude);
    const std::uint64_t int64_limit = 9223372036854775808ull;
    const bool signed64 =
        field.type == FieldDescriptorProto::TYPE_INT64 ||
        field.type == FieldDescriptorProto::TYPE_SINT64 ||
        field.type == FieldDescriptorProto::TYPE_SFIXED64;
    if (signed64 && negative && magnitude == int64_limit) {
        return " = (-9223372036854775807LL - 1)";
    }
    if (!signed64 &&
        (field.type == FieldDescriptorProto::TYPE_UINT64 ||
         field.type == FieldDescriptorProto::TYPE_FIXED64) &&
        magnitude > int64_limit - 1u) {
        return myformat(" = {0}ULL", text);
    }
    return myformat(" = {0}", text);
}


// " = static_cast<Type>(0)". The spelling names no enumerator, so it is the
// one initializer the emitter can write for an enum it cannot see - and, for a
// zero first value, the one it writes for a visible enum declared in another
// file, so the two agreement rules below hold (CR-08, P7).
std::string zero_enum_default(const FieldDescriptorProto& field)
{
    // GCC 4.7 still tokenizes "<::" as the alternative token "<:" followed by
    // ':', so the whole initializer goes through the same separator helper as
    // the field declarations (cpp_type_legacy_safe). The type itself does not
    // contain '<': the digraph is formed by the cast's '<' and the leading
    // "::" of the qualified name.
    return cpp_type_legacy_safe(
        myformat(" = static_cast<{0}>(0)",
                 cpp_qualified_type_str(field.type_name)));
}


// Either " = default_field_value" or empty string.  Enum fields use their
// declared first value as the implicit protobuf default; integer zero cannot
// initialize an enum in standard C++ and may not name a declared value.
//
// `local` holds the enums the generated file itself declares. An enum declared
// in another visible file is spelled through its zero value whenever that
// value is the declared first one: the thin-descriptor compatibility mode
// cannot see the definition at all, and the complete closure must not spell
// the same schema differently (W-68, P7). A non-zero first value keeps the
// enumerator's name, because zero is then not the protobuf default.
std::string default_value_str(const FieldDescriptorProto& field,
                              const EnumByProtoName& enums,
                              const EnumByProtoName& local,
                              const GenerationContext& context)
{
    if (is_repeated(field)) {
        return "";
    }

    if (field.type == FieldDescriptorProto::TYPE_ENUM) {
        const std::string proto_name = view_text(field.type_name);
        const bool explicit_default =
            field.has_default_value && ! context.options.no_default_values;
        const auto found = enums.find(proto_name);

        // Descriptor sets may reference imported enums that are not present in
        // the selected file. The explicit default is kept verbatim (W-47); the
        // implicit one becomes the zero value, so the member is never left
        // indeterminate in compatibility mode (CR-08).
        if (found == enums.end()) {
            return explicit_default
                ? myformat(" = {0}{1}{2}",
                           cpp_qualified_type_str(field.type_name),
                           CPP_TYPE_DELIMITER,
                           easypb_codegen::cpp_identifier(
                               view_text(field.default_value)))
                : zero_enum_default(field);
        }

        const EnumDescriptorProto& enum_type = *found->second;
        if (enum_type.value.empty()) {
            throw std::runtime_error(
                myformat("Enum type '{0}' must contain at least one value", proto_name));
        }

        if (explicit_default) {
            // C++11 permits qualifying an unscoped enumerator through its enum
            // type. This prevents an enumerator in a nearer scope from shadowing
            // the intended value. The enumerator is spelled the way the emitter
            // declares it, so a value named after a keyword is escaped here too.
            return myformat(" = {0}{1}{2}",
                            cpp_qualified_type_str(field.type_name),
                            CPP_TYPE_DELIMITER,
                            easypb_codegen::cpp_identifier(
                                view_text(field.default_value)));
        }

        if (local.find(proto_name) == local.end() &&
            enum_type.value.front().number == 0) {
            return zero_enum_default(field);
        }

        return myformat(" = {0}{1}{2}",
                        cpp_qualified_type_str(field.type_name),
                        CPP_TYPE_DELIMITER,
                        easypb_codegen::cpp_identifier(
                            view_text(enum_type.value.front().name)));
    }

    if (field.has_default_value  &&  ! context.options.no_default_values) {
        // Use default field value specified in .proto file, spelled the way
        // C++ can hold it.
        if (field.type == FieldDescriptorProto::TYPE_FLOAT ||
            field.type == FieldDescriptorProto::TYPE_DOUBLE) {
            return float_default_str(field);
        }
        if (field.type == FieldDescriptorProto::TYPE_STRING ||
            field.type == FieldDescriptorProto::TYPE_BYTES) {
            return string_default_str(field, context);
        }
        if (field.type == FieldDescriptorProto::TYPE_BOOL) {
            return myformat(" = {0}", field.default_value);
        }
        return integral_default_str(field);
    } else {
        // C++ doesn't initialize scalar fields by default, so we need to enforce the initialization
        return field.type == FieldDescriptorProto::TYPE_BOOL
                   ? " = false" :
               is_numeric_field(field)
                   ? " = 0"
               // or another field type
                   : "";
    }
}


// Collect map types represented as the synthetic nested messages.
// The map entry itself is not emitted as a C++ struct; we keep only pointers to
// its key/value fields, indexed by the entry's absolute Protobuf type name.
MapTypeByName collect_map_types(const DescriptorProto& message_type,
                                const std::string& message_proto_name,
                                const easypb_schema::DescriptorPath& message_path)
{
    MapTypeByName result;

    for (std::size_t nested_index = 0;
         nested_index < message_type.nested_type.size(); ++nested_index)
    {
        const auto& nested_msgtype = message_type.nested_type[nested_index];
        if (nested_msgtype.options.map_entry)
        {
            MapType map_type;

            for (const auto& field: nested_msgtype.field)
            {
                switch (field.number) {
                    case 1:  map_type.key_field   = &field;  break;
                    case 2:  map_type.value_field = &field;  break;
                }
            }

            // Three strings became one: `std::string(nested_msgtype.name)` was a
            // copy of a view, the first '+' built another temporary, and the
            // node then copied the key again. Growing one buffer in place and
            // moving it into the node leaves a single allocation.
            std::string qualified_name = message_proto_name;
            qualified_name += PB_TYPE_DELIMITER;
            qualified_name += nested_msgtype.name;

            if (! map_type.key_field || ! map_type.value_field) {
                throw EmitterError(
                    easypb_schema::message_nested_path(
                        message_path, static_cast<int>(nested_index)),
                    myformat("Malformed map entry {0}: fields 1 and 2 are required", qualified_name));
            }

            // The index is keyed by the entry's absolute Protobuf type name, so
            // two nested entries of ONE message cannot both be indexed under
            // it. Such a pair is a duplicate declaration of a single nested
            // type, which the LINKER refuses in both modes as a name collision
            // (`DIAGNOSTIC_DUPLICATE_SYMBOL`), and this CLI never links, so it
            // must refuse the same shape here rather than silently pick one of
            // the two and generate C++ for it (defect-ledger `D-65`). The pick
            // is what the check removes: the pre-2026-09-29 spelling
            // (`result[qualified_name] = map_type`) kept the LAST entry and the
            // `insert` it became keeps the FIRST, so the same bytes generated
            // different C++ - `put_map_string_int32` against
            // `put_map_bytes_string` - depending on the spelling alone.
            if (result.find(qualified_name) != result.end()) {
                throw EmitterError(
                    easypb_schema::message_nested_path(
                        message_path, static_cast<int>(nested_index)),
                    myformat("Duplicate map entry {0}: a nested map entry with this name is already declared",
                             qualified_name));
            }

            result.insert(MapTypeByName::value_type(std::move(qualified_name),
                                                   map_type));
        }
    }

    return result;
}


// If field is a generated map field, return metadata for its synthetic map-entry
// message. Ordinary repeated message fields return nullptr. TYPE_GROUP remains
// unsupported as a map value even though message values are allowed.
const MapType* find_map_type(const FieldDescriptorProto& field,
                             const MapTypeByName& maptype_by_name,
                             str_view message_cpp_name,
                             const easypb_schema::DescriptorPath& field_path)
{
    if (maptype_by_name.empty() || ! is_repeated(field) ||
        field.type != FieldDescriptorProto::TYPE_MESSAGE) {
        return nullptr;
    }

    // The index is keyed by the entry's absolute type name, and a C++11
    // std::map cannot look a str_view up without first building the owned key
    // (heterogeneous comparison and the templated `find` are C++14). The index
    // holds one entry per map field of ONE message, so a linear comparison is
    // the bounded scan that avoids the per-field copy the lookup used to make
    // (W-62). Insertion order, keys and the duplicate check are unchanged.
    const MapType* map_type = 0;
    for (MapTypeByName::const_iterator it = maptype_by_name.begin();
         it != maptype_by_name.end(); ++it) {
        if (it->first == field.type_name) {
            map_type = &it->second;
            break;
        }
    }
    if (map_type == 0) {
        return nullptr;
    }

    // These pointers refer to metadata owned by the map index and descriptor.
    const FieldDescriptorProto* value_field = map_type->value_field;
    auto value_type = value_field->type;

    if (value_type == FieldDescriptorProto::TYPE_GROUP)
    {
        throw EmitterError(
            field_path,
            myformat("Unsupported map value type '{0}' for field {1}.{2}",
                     pbtype_name(*value_field), message_cpp_name, field.name));
    }

    return map_type;
}


// Codegen-side description of one real Protobuf message.  It complements the
// descriptor with the names needed for C++ output and with resolved dependencies.
// `children` contains lexical nested messages but deliberately excludes synthetic
// map-entry messages.  Objects live inside the root `std::vector<MessageInfo>`;
// pointers stored in `dependencies` are filled only after that tree is complete.
// `dependencies` is the C++ definition-dependency graph: it contains only
// references whose target type must be complete before this message definition
// is emitted, not necessarily every Protobuf type reference.
struct MessageInfo
{
    const DescriptorProto* descriptor = nullptr;
    std::string simple_name;          // Inner
    std::string cpp_name;             // Inner_ (the C++ struct name)
    std::string proto_name;           // .pkg.Outer.Inner
    std::string cpp_absolute_name;    // ::pkg::Outer::Inner
    std::string macro_stem;           // EASYPB_Outer_Inner (legacy spelling)
    // The declaration this subtree came from, so every refusal about it can be
    // positioned in the source file (U-30).
    easypb_schema::DescriptorPath path;
    MapTypeByName map_types;
    std::vector<MessageInfo> children;
    std::vector<MessageInfo*> dependencies;
};


// Absolute Protobuf type name -> MessageInfo.  This lets fields resolved by the
// parser/protoc be connected back to the message that Codegen will emit.
// In C++17 mode the key is a view into MessageInfo::proto_name or descriptor storage,
// so lookups avoid copying.
using MessageByProtoName = std::map<str_view, MessageInfo*>;


// Build the lexical MessageInfo tree and its distinct Protobuf/C++ name forms in one recursive walk.
// Synthetic map entries stay in DescriptorProto::nested_type for map metadata,
// but are not added to the user-visible message tree.
MessageInfo make_message_info(const DescriptorProto& descriptor,
                              const std::string& parent_proto_name,
                              const GenerationContext& context,
                              const easypb_schema::DescriptorPath& path)
{
    MessageInfo info;
    info.descriptor = &descriptor;
    info.path = path;
    info.simple_name = descriptor.name;
    // The C++ name of the struct. A name that is a C++ keyword is escaped,
    // exactly as the reference compiler escapes it (compiler/cpp/helpers.cc:
    // 451-459 spells the class of a schema that declares `message class`
    // `class_`). The Protobuf name keeps the raw spelling: it is the key of
    // the symbol index and the name a type reference resolves against.
    //
    // The whole name derivation is one declaration's work, so a refusal in the
    // name layer is positioned at this message (U-30).
    try {
        info.cpp_name = easypb_codegen::cpp_identifier(info.simple_name);
        info.proto_name = parent_proto_name.empty()
            ? context.package_name_prefix + info.simple_name
            : parent_proto_name + PB_TYPE_DELIMITER + info.simple_name;
        info.cpp_absolute_name =
            easypb_codegen::cpp_absolute_name(info.proto_name);
        info.macro_stem = easypb_codegen::insertion_macro_stem(
            info.proto_name, context.package);
    } catch (const std::exception& problem) {
        throw EmitterError(path, problem.what());
    }

    for (std::size_t i = 0; i < descriptor.nested_type.size(); ++i) {
        const DescriptorProto& nested = descriptor.nested_type[i];
        if (! nested.options.map_entry) {
            info.children.push_back(make_message_info(
                nested, info.proto_name, context,
                easypb_schema::message_nested_path(path,
                                                   static_cast<int>(i))));
        }
    }

    return info;
}


// Add every real message in one lexical subtree to the absolute-name index.
void index_message_info(MessageInfo& info, MessageByProtoName& index)
{
    index[info.proto_name] = &info;
    for (auto& child: info.children) {
        index_message_info(child, index);
    }
}


// Flatten a MessageInfo subtree into pointers without changing source order.
// Several graph operations use this instead of duplicating recursive walks.
void collect_message_infos(MessageInfo& info, std::vector<MessageInfo*>& output)
{
    output.push_back(&info);
    for (auto& child: info.children) {
        collect_message_infos(child, output);
    }
}


// A nested C++ type is declared inside its ancestor.  If it stores that ancestor
// by value, no declaration order can make the C++ type complete, so this is a
// recursive value dependency even before general graph-cycle detection.
// True when `name` lies strictly under the lexical scope `prefix`, that is when
// `prefix` is its own head followed by the component separator. The comparison
// is allocation-free, and the dependency walk asks it once per lexical unit per
// dependency - the widest loop in the graph pass.
bool is_under_proto_scope(const std::string& name, const std::string& prefix)
{
    return name.size() > prefix.size() &&
           name.compare(0, prefix.size(), prefix) == 0 &&
           name[prefix.size()] == '.';
}

bool is_ancestor_message(const MessageInfo& ancestor, const MessageInfo& message)
{
    return message.proto_name != ancestor.proto_name &&
           is_under_proto_scope(message.proto_name, ancestor.proto_name);
}


// Keep dependency lists unique; one message may mention the same type in many fields.
void add_dependency(MessageInfo& source, MessageInfo* target)
{
    if (! target) return;
    for (auto* dependency: source.dependencies) {
        if (dependency == target) return;
    }
    source.dependencies.push_back(target);
}


// Return whether this field requires the target C++ message definition to be
// complete before the owning message can be emitted.  Today the only exception
// is an explicitly enabled direct self-reference through a repeated field or a
// map value.  Keeping this as a semantic decision point also leaves room for
// future indirect/pointer-like message storage, which likewise may not require
// a complete target type at structure-definition time.
bool requires_definition_dependency(const MessageInfo& owner,
                                    const FieldDescriptorProto& field,
                                    const FieldDescriptorProto& dependency_field,
                                    const MapType* map_type,
                                    const MessageInfo* target,
                                    const GenerationContext& context)
{
    if (context.options.allow_self_recursive_containers &&
        target == &owner &&
        dependency_field.type == FieldDescriptorProto::TYPE_MESSAGE &&
        (map_type || field.label == FieldDescriptorProto::LABEL_REPEATED))
    {
        return false;
    }

    return true;
}


// Resolve the message definition required by a field's user-defined type.
// Message fields need their target message, while nested enum fields need the
// message that owns the enum. Top-level enums have no message dependency.
MessageInfo* find_type_owner(const FieldDescriptorProto& field,
                             const MessageByProtoName& index)
{
    if (field.type == FieldDescriptorProto::TYPE_MESSAGE) {
        auto found = index.find(field.type_name);
        return found == index.end() ? nullptr : found->second;
    }

    if (field.type == FieldDescriptorProto::TYPE_ENUM) {
        const std::size_t separator = field.type_name.rfind(PB_TYPE_DELIMITER);
        if (separator == str_view::npos) return nullptr;
        const str_view owner_name = field.type_name.substr(0, separator);
        auto found = index.find(owner_name);
        return found == index.end() ? nullptr : found->second;
    }

    return nullptr;
}


// Resolve declaration dependencies between messages emitted from this file.
// Message fields depend directly on field.type_name; nested enum fields depend
// on the message that owns the enum. Maps use their synthetic entry's value
// field, so map<string, Child> depends on Child rather than hidden XxxEntry.
//
// External message/enum names are intentionally ignored here: source generation
// has already rejected unresolved imports, while descriptor-set mode preserves
// the existing behavior for types Codegen does not itself define.
void resolve_message_dependencies(MessageInfo& info,
                                  const MessageByProtoName& index,
                                  const GenerationContext& context)
{
    info.map_types = collect_map_types(*info.descriptor, info.proto_name,
                                       info.path);

    for (std::size_t field_index = 0;
         field_index < info.descriptor->field.size(); ++field_index) {
        const FieldDescriptorProto& field = info.descriptor->field[field_index];
        const easypb_schema::DescriptorPath field_path =
            easypb_schema::message_field_path(info.path,
                                              static_cast<int>(field_index));
        const MapType* map_type = find_map_type(field, info.map_types,
                                                info.cpp_absolute_name,
                                                field_path);
        const FieldDescriptorProto& dependency_field =
            map_type ? *map_type->value_field : field;
        MessageInfo* target = find_type_owner(dependency_field, index);
        if (! target) continue;

        const bool needs_definition = requires_definition_dependency(
            info, field, dependency_field, map_type, target, context);

        if (dependency_field.type == FieldDescriptorProto::TYPE_MESSAGE &&
            needs_definition &&
            is_ancestor_message(*target, info))
        {
            throw EmitterError(
                field_path,
                myformat("recursive message value dependency: {0} -> {1}",
                         info.cpp_absolute_name, target->cpp_absolute_name));
        }

        // An enum declared by this message or an ancestor is already visible
        // before this message's fields; it must not create a graph self-cycle.
        if (dependency_field.type == FieldDescriptorProto::TYPE_ENUM &&
            (target == &info || is_ancestor_message(*target, info)))
        {
            continue;
        }
        if (needs_definition) {
            add_dependency(info, target);
        }
    }

    for (auto& child: info.children) {
        resolve_message_dependencies(child, index, context);
    }
}


// Reject every by-value cycle before any generated text is returned to main().
//
// A back edge reconstructs the cycle in C++ names so the error explains why
// by-value generation is impossible. The walk keeps its own stack instead of
// calling itself: the graph depth is schema-controlled (a chain of N messages
// has N edges), and the recursive form overflowed the process stack on a
// 12 000-message chain (CR-35). Each frame is one node plus the index of the
// next dependency to examine - what a recursive call keeps in its loop
// variable and program counter.
void detect_dependency_cycles(std::vector<MessageInfo>& roots)
{
    std::map<MessageInfo*, GraphColor> color;
    std::vector<MessageInfo*> all_messages;
    for (auto& root: roots) collect_message_infos(root, all_messages);
    for (auto* message: all_messages) color[message] = GraphColor::Unvisited;

    struct Frame
    {
        MessageInfo* message;
        std::size_t next;
    };

    // The DFS path itself, in visit order; a cycle report is its suffix from
    // the repeated node.
    std::vector<Frame> stack;
    for (auto* message: all_messages) {
        if (color[message] != GraphColor::Unvisited) continue;

        color[message] = GraphColor::OnStack;
        stack.push_back(Frame{message, 0});
        while (! stack.empty()) {
            Frame& frame = stack.back();
            if (frame.next >= frame.message->dependencies.size()) {
                color[frame.message] = GraphColor::Finished;
                stack.pop_back();
                continue;
            }

            MessageInfo* dependency = frame.message->dependencies[frame.next++];
            if (color[dependency] == GraphColor::Unvisited) {
                color[dependency] = GraphColor::OnStack;
                stack.push_back(Frame{dependency, 0});
            } else if (color[dependency] == GraphColor::OnStack) {
                std::string path;
                std::size_t start = 0;
                while (start < stack.size() &&
                       stack[start].message != dependency) {
                    ++start;
                }
                for (std::size_t i = start; i < stack.size(); ++i) {
                    if (! path.empty()) path += " -> ";
                    path += stack[i].message->cpp_absolute_name;
                }
                if (! path.empty()) path += " -> ";
                path += dependency->cpp_absolute_name;
                throw EmitterError(
                    dependency->path,
                    "recursive message value dependency: " + path);
            }
        }
    }
}


// Stable topological ordering for a set of sibling lexical subtrees.
// A dependency between any two messages inside different subtrees becomes a
// dependency between the corresponding roots.  Dependencies are visited in
// original source order so unrelated messages retain their previous order.
//
// The walk is O(units + dependency edges): the message-to-unit owner map is
// built once, and every frame walks its own edge list.  Scanning all units for
// each frame made a 12 000-message value chain O(n^2) and timed out the
// Debug CTest lane on the oldest MSVC toolset (CR-35 fixture), even though the
// result was correct.
std::vector<MessageInfo*> stable_topological_order(const std::vector<MessageInfo*>& units)
{
    // Collapse field-level dependencies to the sibling/root granularity that
    // can actually be reordered in C++ source.  `owner` answers "which unit
    // contains this message" once, instead of the prefix scan that used to
    // run for every field dependency.
    std::vector<std::vector<MessageInfo*> > subtrees(units.size());
    std::map<MessageInfo*, std::size_t> owner;
    for (std::size_t i = 0; i < units.size(); ++i) {
        collect_message_infos(*units[i], subtrees[i]);
        for (auto* message: subtrees[i]) owner[message] = i;
    }

    std::vector<std::vector<std::size_t> > dependencies(units.size());
    for (std::size_t i = 0; i < units.size(); ++i) {
        std::vector<std::size_t>& unit_deps = dependencies[i];
        for (auto* source: subtrees[i]) {
            for (auto* dependency: source->dependencies) {
                const std::map<MessageInfo*, std::size_t>::const_iterator found =
                    owner.find(dependency);
                if (found != owner.end() && found->second != i) {
                    unit_deps.push_back(found->second);
                }
            }
        }
        std::sort(unit_deps.begin(), unit_deps.end());
        unit_deps.erase(std::unique(unit_deps.begin(), unit_deps.end()),
                        unit_deps.end());
    }

    std::vector<GraphColor> color(units.size(), GraphColor::Unvisited);
    std::vector<MessageInfo*> result;
    result.reserve(units.size());

    // The same explicit stack as the cycle walk (CR-35): a chain of lexical
    // subtrees is as deep as its dependency chain, so a recursive visitor
    // overflows on a schema the generator otherwise accepts. The dependency
    // list is sorted by source position, so this is the same visiting order
    // the former full-unit scan produced, without the scan.
    struct Frame
    {
        std::size_t unit;
        std::size_t next;
    };

    std::vector<Frame> stack;
    for (std::size_t root = 0; root < units.size(); ++root) {
        if (color[root] != GraphColor::Unvisited) continue;

        color[root] = GraphColor::OnStack;
        stack.push_back(Frame{root, 0});
        while (! stack.empty()) {
            Frame& frame = stack.back();
            const std::vector<std::size_t>& unit_deps =
                dependencies[frame.unit];
            if (frame.next >= unit_deps.size()) {
                color[frame.unit] = GraphColor::Finished;
                result.push_back(units[frame.unit]);  // dependencies first
                stack.pop_back();
                continue;
            }

            const std::size_t candidate = unit_deps[frame.next++];
            if (color[candidate] == GraphColor::Unvisited) {
                color[candidate] = GraphColor::OnStack;
                stack.push_back(Frame{candidate, 0});
            } else if (color[candidate] == GraphColor::OnStack) {
                // This is a cycle between lexical units (for example, two
                // root structs whose nested messages depend on each other).
                std::string path;
                std::size_t start = 0;
                while (start < stack.size() &&
                       stack[start].unit != candidate) {
                    ++start;
                }
                for (std::size_t i = start; i < stack.size(); ++i) {
                    if (! path.empty()) path += " -> ";
                    path += units[stack[i].unit]->cpp_absolute_name;
                }
                if (! path.empty()) path += " -> ";
                path += units[candidate]->cpp_absolute_name;
                throw EmitterError(
                    units[candidate]->path,
                    "recursive message value dependency: " + path);
            }
        }
    }
    return result;
}


// Collect sibling/root messages and return them in dependency-safe declaration
// order, so every value-type dependency is emitted before its first use.
std::vector<MessageInfo*> dependency_safe_order(std::vector<MessageInfo>& messages)
{
    std::vector<MessageInfo*> units;
    units.reserve(messages.size());
    for (auto& message: messages) units.push_back(&message);
    if (units.size() <= 1) return units;
    return stable_topological_order(units);
}


// The members of one message's struct.
//
// The struct holds six kinds of declaration, and all six live in the same
// C++ scope: the fields, the presence flags, the nested enums, the
// enumerators of those enums, the nested messages and the struct's own name.
// (The free codec functions spell the same names, but they live at file
// scope.) Two of them can ask for the same name even when the Protobuf names
// are all different:
//
//   - the presence flag of a field is named after the field, so the field
//     `foo` wants the flag `has_foo` and the field `has_foo` wants the
//     member `has_foo`;
//   - a nested type is a member of its parent, so the nested message
//     `has_foo` wants the member `has_foo` as well;
//   - an unscoped enum's enumerators are members of the enclosing struct,
//     not of the enum: the value `has_foo` of a nested enum is a sibling of
//     the field `foo` and of its presence flag (CR-03);
//   - the escape rule is not injective, so the fields `class` and `class_`
//     both want the member `class_`, and so do the values `class` and
//     `class_` of two different nested enums;
//   - the class's own name is a declaration of its own scope (U-01): C++
//     refuses a nested type or an enumerator that carries it ("'Outer::Outer'
//     has the same name as the class in which it is declared") although the
//     reference compiler accepts `message Outer { message Outer { ... } }`
//     and renames it to `Outer_Outer`. A field or a presence flag of that
//     name is legal C++ and stays accepted (cpp_declarations_conflict).
//
// The reference compiler accepts the first two shapes. In proto3 a scalar
// field has no presence accessor, so nothing collides there; in proto2 it
// generates two accessors that differ only in their return type, which C++
// forbids - and there is no working protoc output to match. A nested type
// does not collide there either: protoc flattens it to `Outer_HasFoo` and
// spells its accessors as methods. So a diagnostic is the better answer.
//
// The check is gated on the generation options and not on the schema: the
// flag exists only while the flags are enabled, so a run with
// --no-has-fields accepts the shape. The other kinds are always declared,
// and the codecs spell them even under --no-class, so they are always
// listed.
std::vector<ScopeMember> message_scope_members(const MessageInfo& info,
                                                const GenerationContext& context)
{
    std::vector<ScopeMember> members;
    // The struct's own name comes first, so a diagnostic names the class
    // before the declaration that collides with it.
    ScopeMember enclosing;
    enclosing.cpp_name = info.cpp_name;
    enclosing.description = member_description("message", info.simple_name);
    enclosing.kind = SCOPE_MEMBER_ENCLOSING_TYPE;
    enclosing.path = info.path;
    members.push_back(enclosing);
    for (std::size_t i = 0; i < info.descriptor->field.size(); ++i) {
        const auto& field = info.descriptor->field[i];
        ScopeMember member;
        member.path = easypb_schema::message_field_path(
            info.path, static_cast<int>(i));
        member.cpp_name = field_member_name_at(field, member.path);
        member.description = member_description("field",
                                                view_text(field.name));
        member.kind = SCOPE_MEMBER_FIELD;
        members.push_back(member);
    }
    for (std::size_t i = 0; i < info.descriptor->field.size(); ++i) {
        const auto& field = info.descriptor->field[i];
        if (! hasfield_enabled(field, context)) continue;
        ScopeMember member;
        member.path = easypb_schema::message_field_path(
            info.path, static_cast<int>(i));
        member.cpp_name = field_flag_name_at(field, member.path);
        member.description =
            myformat("presence flag of the field '{0}'",
                     view_text(field.name));
        member.kind = SCOPE_MEMBER_PRESENCE_FLAG;
        members.push_back(member);
    }
    for (std::size_t i = 0; i < info.descriptor->enum_type.size(); ++i) {
        const auto& enum_type = info.descriptor->enum_type[i];
        const easypb_schema::DescriptorPath enum_path =
            easypb_schema::message_enum_path(info.path,
                                             static_cast<int>(i));
        ScopeMember member;
        member.path = enum_path;
        member.cpp_name = cpp_identifier_at(view_text(enum_type.name),
                                            enum_path);
        member.description = member_description("nested enum",
                                                view_text(enum_type.name));
        member.kind = SCOPE_MEMBER_TYPE;
        members.push_back(member);
        // An unscoped enum's enumerators belong to the scope that declares
        // the enum, not to the enum: `M::E::has_foo` and `M::has_foo` are
        // the same declaration (CR-03).
        for (std::size_t j = 0; j < enum_type.value.size(); ++j) {
            const auto& value = enum_type.value[j];
            ScopeMember enumerator;
            enumerator.path = easypb_schema::enum_value_path(
                enum_path, static_cast<int>(j));
            enumerator.cpp_name = cpp_identifier_at(
                view_text(value.name), enumerator.path);
            enumerator.description = member_description(
                "enum value", view_text(value.name));
            enumerator.kind = SCOPE_MEMBER_ENUMERATOR;
            members.push_back(enumerator);
        }
    }
    for (std::size_t i = 0; i < info.children.size(); ++i) {
        ScopeMember member;
        member.path = info.children[i].path;
        member.cpp_name = info.children[i].cpp_name;
        member.description = member_description("nested message",
                                                info.children[i].simple_name);
        member.kind = SCOPE_MEMBER_TYPE;
        members.push_back(member);
    }
    return members;
}


// The runtime types `include/easypb.hpp` declares in `namespace easypb`.
//
// Owner decision #1 (DECISIONS.md) allows `package easypb;` and treats these
// names as occupants of the file scope: with that package the generated
// namespace IS the runtime namespace, so `message Encoder` redefines
// `easypb::Encoder` and the header does not compile. The list is the seven
// types the decision names, in declaration order of the runtime header.
const char* const EASYPB_RUNTIME_TYPES[] = {
    "Encoder", "Decoder", "Writer", "Reader", "WireType", "PBType",
    "string_view"
};


// The declarations of one file's scope.
//
// A file's scope holds the top-level messages, the top-level enums, the
// enumerators of those enums, the two free codec overloads and the names the
// generated preamble already owns: in an un-packaged schema the two runtime
// namespaces every header references (CR-09) and the global typedefs of
// <cstdint> and <cstddef> (U-03), and with `package easypb;` the runtime types
// themselves (U-02). A nested declaration belongs to the scope of its own
// parent.
//
// The codec functions are emitted only when their option is on (CR-04), and
// the runtime namespaces are global names only when the package is empty
// (CR-09). The check is run with the same options that drive the emitter, so
// a name is refused exactly when the declaration that owns it is emitted.
void check_file_scope_names(const FileDescriptorProto& file,
                            const std::vector<MessageInfo>& roots,
                            const GenerationContext& context)
{
    std::vector<ScopeMember> members;
    for (std::size_t i = 0; i < file.enum_type.size(); ++i) {
        const auto& enum_type = file.enum_type[i];
        const easypb_schema::DescriptorPath enum_path =
            easypb_schema::file_enum_path(static_cast<int>(i));
        ScopeMember member;
        member.path = enum_path;
        member.cpp_name = cpp_identifier_at(view_text(enum_type.name),
                                            enum_path);
        member.description = member_description("enum",
                                                view_text(enum_type.name));
        member.kind = SCOPE_MEMBER_TYPE;
        members.push_back(member);
        for (std::size_t j = 0; j < enum_type.value.size(); ++j) {
            const auto& value = enum_type.value[j];
            ScopeMember enumerator;
            enumerator.path = easypb_schema::enum_value_path(
                enum_path, static_cast<int>(j));
            enumerator.cpp_name = cpp_identifier_at(
                view_text(value.name), enumerator.path);
            enumerator.description = member_description(
                "enum value", view_text(value.name));
            enumerator.kind = SCOPE_MEMBER_ENUMERATOR;
            members.push_back(enumerator);
        }
    }
    for (std::size_t i = 0; i < roots.size(); ++i) {
        ScopeMember member;
        member.path = roots[i].path;
        member.cpp_name = roots[i].cpp_name;
        member.description = member_description("message",
                                                roots[i].simple_name);
        member.kind = SCOPE_MEMBER_TYPE;
        members.push_back(member);
    }
    if (! context.options.no_encoder) {
        ScopeMember member;
        member.cpp_name = "encode";
        member.description = member_description("generated encoder function",
                                                "encode");
        member.kind = SCOPE_MEMBER_CODEC;
        members.push_back(member);
    }
    if (! context.options.no_decoder) {
        ScopeMember member;
        member.cpp_name = "decode";
        member.description = member_description("generated decoder function",
                                                "decode");
        member.kind = SCOPE_MEMBER_CODEC;
        members.push_back(member);
    }
    if (context.package.empty()) {
        ScopeMember easypb;
        easypb.cpp_name = "easypb";
        easypb.description =
            member_description("runtime namespace", "easypb");
        easypb.kind = SCOPE_MEMBER_GLOBAL_NAME;
        members.push_back(easypb);
        ScopeMember std_namespace;
        std_namespace.cpp_name = "std";
        std_namespace.description =
            member_description("standard library namespace", "std");
        std_namespace.kind = SCOPE_MEMBER_GLOBAL_NAME;
        members.push_back(std_namespace);
        // U-03: the global typedefs the header's own preamble declares. The
        // emitter spells every scalar type absolutely (`::int32_t`), so a
        // declaration in the GLOBAL namespace that owns one of these names is
        // a redefinition of a typedef the header itself uses. Inside a package
        // the same name is legal and is not shadowed - the qualified spelling
        // is why `tests/codegen/packages/data/shadow.proto` declares
        // `message int32_t` in `package app.std.easypb` and stays accepted -
        // so the occupancy is the same "no package" case as the namespaces
        // above.
        const std::set<std::string>& global_names =
            easypb_codegen::cpp_global_names();
        for (std::set<std::string>::const_iterator it = global_names.begin();
             it != global_names.end(); ++it) {
            ScopeMember member;
            member.cpp_name = *it;
            member.description = member_description("global typedef", *it);
            member.kind = SCOPE_MEMBER_GLOBAL_NAME;
            members.push_back(member);
        }
    }
    if (context.package == "easypb") {
        // U-02: the file's declarations open `namespace easypb`, the one the
        // runtime header already declares its types in. The package itself is
        // allowed (owner decision #1); a type that carries one of those names
        // is refused, naming both occupants.
        for (std::size_t i = 0;
             i < sizeof(EASYPB_RUNTIME_TYPES) / sizeof(EASYPB_RUNTIME_TYPES[0]);
             ++i) {
            ScopeMember member;
            member.cpp_name = EASYPB_RUNTIME_TYPES[i];
            member.description = member_description("runtime type",
                                                    EASYPB_RUNTIME_TYPES[i]);
            member.kind = SCOPE_MEMBER_GLOBAL_NAME;
            members.push_back(member);
        }
    }
    refuse_duplicate_cpp_names(members, "the file scope");
}


// Generate one message subtree in a single recursive walk.  The return value is
// the C++ struct text that must be embedded in the parent.  Encoder and decoder
// text is accumulated separately so all type definitions can be printed before
// any free codec functions, without making a second pass over the descriptor.
std::string generate_message(MessageInfo& info,
                             const std::string& indent,
                             const EnumByProtoName& enum_index,
                             const EnumByProtoName& local_enum_index,
                             std::string& encoders,
                             std::string& decoders,
                             const GenerationContext& context)
{
    std::string nested_defs;
    if (! info.descriptor->enum_type.empty() || ! info.children.empty()) {
        const std::string child_indent = indent + CPP_INDENT;
        // Enum declarations precede nested messages and fields that may use them.
        for (std::size_t i = 0; i < info.descriptor->enum_type.size(); ++i) {
            const auto& enum_type = info.descriptor->enum_type[i];
            const easypb_schema::DescriptorPath enum_path =
                easypb_schema::message_enum_path(info.path,
                                                 static_cast<int>(i));
            // The enumerators live in the enum's own scope, and the escape
            // rule is not injective: `class` and `class_` would both be
            // spelled `class_`. The check runs even when the classes are not
            // generated: the codecs spell the enumerators, so the collision
            // would reach the caller's own declaration.
            check_enum_value_names(enum_type, enum_path);
            nested_defs += generate_enum(enum_type, child_indent, enum_path);
        }
        for (auto* child: dependency_safe_order(info.children)) {
            nested_defs += generate_message(
                *child, child_indent, enum_index, local_enum_index, encoders,
                decoders, context);
        }
    }

    std::string field_defs, has_field_defs, encoder, decoder, check_required_fields;

    // The C++ scope of this struct: its fields, its presence flags, its
    // nested types and the enumerators of its nested enums. Two declarations
    // of it cannot carry the same C++ name.
    refuse_duplicate_cpp_names(message_scope_members(info, context),
                               myformat("message '{0}'", info.proto_name));

    for (std::size_t field_index = 0;
         field_index < info.descriptor->field.size(); ++field_index)
    {
        const FieldDescriptorProto& field = info.descriptor->field[field_index];
        // The declaration this field's refusal is about (U-30). Every helper
        // below reads one field, so one wrapper positions them all.
        const easypb_schema::DescriptorPath field_path =
            easypb_schema::message_field_path(info.path,
                                              static_cast<int>(field_index));
        try {
            auto map_type = find_map_type(field, info.map_types,
                                          info.cpp_absolute_name, field_path);

            // The member type and its template validation belong to the schema
            // (the empty-type option is refused on the source door while that
            // text is parsed), so the spelling is asked for under every option
            // set even though `--no-class` discards it.
            auto cpptype_str = cpp_type_as_str(field, map_type, context);

            // U-20: the member declaration and its default-value initializer are
            // emitted only when the class is. A member default-value refusal
            // describes a member this run does not write - `--no-class` leaves
            // the caller to declare it - so the initializer is not built at all.
            // The schema-level validation that owns field numbers, types and
            // defaults has already run in the semantics layer and is not
            // affected.
            if (! context.options.no_class) {
                field_defs += myformat(
                    "{0}    {1} {2}{3};\n", indent, cpptype_str,
                    field_member_name(field),
                    default_value_str(field, enum_index, local_enum_index,
                                      context));

                if (hasfield_enabled(field, context)) {
                    has_field_defs += myformat(
                        "{0}    bool {1} = false;\n",
                        indent, field_flag_name(field));
                }
            }

            // Field codecs still use the same helpers as top-level messages;
            // only the enclosing type name and output section have changed.
            encoder += generate_field_encoder(field, map_type, context);
            decoder += generate_field_decoder(field, map_type, context);

            if ((field.label == FieldDescriptorProto::LABEL_REQUIRED) && ! context.options.no_required) {
                check_required_fields += myformat(
                    CHECK_REQUIRED_FIELD_TEMPLATE, info.cpp_absolute_name,
                    field_flag_name(field),
                    view_text(field.name));
            }
        } catch (const EmitterError&) {
            throw;
        } catch (const std::exception& problem) {
            throw EmitterError(field_path, problem.what());
        }
    }

    // Codec functions are emitted for every real message, including nested
    // ones. Their signatures use qualified C++ names such as Outer::Inner.
    if (! context.options.no_encoder) {
        encoders += myformat(ENCODER_TEMPLATE, info.cpp_absolute_name, info.macro_stem, encoder);
    }
    if (! context.options.no_decoder) {
        decoders += myformat(DECODER_TEMPLATE, info.cpp_absolute_name, info.macro_stem,
                             decoder, check_required_fields);
    }

    if (context.options.no_class) return "";
    return myformat(CLASS_TEMPLATE, indent, info.cpp_name, nested_defs,
                    field_defs, has_field_defs, info.macro_stem);
}


// Emit C++11-compatible namespace blocks for a protobuf package.
std::string open_package_namespaces(const std::string& package)
{
    if (package.empty()) return "";

    std::string result;
    std::size_t start = 0;
    while (start < package.size()) {
        const std::size_t end = package.find('.', start);
        const std::string component = package.substr(
            start, end == std::string::npos ? std::string::npos : end - start);
        result += "namespace " + component + " {\n";
        if (end == std::string::npos) break;
        start = end + 1;
    }
    result += "\n";
    return result;
}


std::string close_package_namespaces(const std::string& package)
{
    if (package.empty()) return "";

    std::vector<std::string> components;
    std::size_t start = 0;
    while (start < package.size()) {
        const std::size_t end = package.find('.', start);
        components.push_back(package.substr(
            start, end == std::string::npos ? std::string::npos : end - start));
        if (end == std::string::npos) break;
        start = end + 1;
    }

    std::string result = "\n";
    for (std::size_t i = components.size(); i > 0; --i) {
        result += "} // namespace " + components[i - 1] + "\n";
    }
    return result;
}


