// {3}=field_defs, {4}=has_field_defs, {5}=macro-safe qualified name
const char* CLASS_TEMPLATE = R"---({0}struct {1}
{0}{
{2}{3}
{4}
{0}    #ifdef EASYPB_{5}_EXTRA_FIELDS
{0}        EASYPB_{5}_EXTRA_FIELDS
{0}    #endif
{0}};

)---";


// {0}=qualified C++ message name, {1}=macro-safe qualified name, {2}=encoder
const char* ENCODER_TEMPLATE = R"---(
inline void encode(easypb::Encoder &pb, const {0} &x)
{
{2}
    #ifdef EASYPB_{1}_EXTRA_ENCODING
        EASYPB_{1}_EXTRA_ENCODING(pb, x)
    #endif
}
)---";


// {0}=qualified C++ message name, {1}=macro-safe qualified name,
// {2}=decoder, {3}=check_required_fields
const char* DECODER_TEMPLATE = R"---(
inline void decode(easypb::Decoder pb, {0} &x)
{
    while(pb.get_next_field())
    {
        switch(pb.field_num)
        {
{2}
            #ifdef EASYPB_{1}_EXTRA_DECODING
                EASYPB_{1}_EXTRA_DECODING(pb, x)
            #endif
            default: pb.skip_field();
        }
    }
    #ifdef EASYPB_{1}_EXTRA_POST_DECODING
        EASYPB_{1}_EXTRA_POST_DECODING(pb, x)
    #endif
{3}}
)---";


// {0}=qualified message name, {1}=field.name
const char* CHECK_REQUIRED_FIELD_TEMPLATE = R"---(
    if(! x.has_{1}) {
        throw easypb::missing_required_field("Decoded protobuf has no required field {0}.{1}");
    }
)---";


// Is it a repeated Protobuf field?
bool is_repeated(const FieldDescriptorProto& field)
{
    return (field.label == FieldDescriptorProto::LABEL_REPEATED);
}


// Does this field have corresponding has_* flag?
bool hasfield_enabled(const FieldDescriptorProto& field)
{
    return (! is_repeated(field)  &&  ! option.no_has_fields);
}


// Is it a Protobuf numeric field (including enums/bools)?
bool is_numeric_field(const FieldDescriptorProto& field)
{
    return (field.type != FieldDescriptorProto::TYPE_STRING) &&
           (field.type != FieldDescriptorProto::TYPE_BYTES) &&
           (field.type != FieldDescriptorProto::TYPE_MESSAGE) &&
           (field.type != FieldDescriptorProto::TYPE_GROUP);
}


// Serialize this field in the more compact "packed" Protobuf wire format?
bool write_as_packed(const FieldDescriptorProto& field)
{
    return is_repeated(field) &&
           is_numeric_field(field) &&
           (option.packed ?    true :
            option.no_packed ? false :
            field.options.has_packed ? field.options.packed :
                                       current_file_is_proto3);
}


// Either " = default_field_value" or empty string
std::string default_value_str(const FieldDescriptorProto& field)
{
    if (field.has_default_value  &&  ! option.no_default_values) {
        // Use default field value specified in .proto file
        bool is_bytearray_field = (field.type==FieldDescriptorProto::TYPE_STRING || field.type==FieldDescriptorProto::TYPE_BYTES);
        const char* quote_str = (is_bytearray_field? "\"" : "");
        return myformat(" = {0}{1}{0}", quote_str, field.default_value);
    } else if (is_repeated(field)) {
        return "";
    } else if (field.type == FieldDescriptorProto::TYPE_ENUM) {
        // An integer literal cannot initialize an enum in standard C++.
        return "";
    } else {
        // C++ doesn't initialize scalar fields by default, so we need to enforce the initialization
        return field.type == FieldDescriptorProto::TYPE_BOOL
                   ? " = false" :
               is_numeric_field(field)
                   ? " = 0"
               // or another field type
                   : "";
    }
}


// PB type as used in .proto file (e.g. "fixed32")
str_view pbtype_name(const FieldDescriptorProto& field)
{
    switch(field.type)
    {
        case FieldDescriptorProto::TYPE_DOUBLE:    return "double";
        case FieldDescriptorProto::TYPE_FLOAT:     return "float";
        case FieldDescriptorProto::TYPE_INT64:     return "int64";
        case FieldDescriptorProto::TYPE_UINT64:    return "uint64";
        case FieldDescriptorProto::TYPE_INT32:     return "int32";
        case FieldDescriptorProto::TYPE_FIXED64:   return "fixed64";
        case FieldDescriptorProto::TYPE_FIXED32:   return "fixed32";
        case FieldDescriptorProto::TYPE_BOOL:      return "bool";
        case FieldDescriptorProto::TYPE_STRING:    return "string";
        case FieldDescriptorProto::TYPE_GROUP:     return "???group";
        case FieldDescriptorProto::TYPE_MESSAGE:   return "message";
        case FieldDescriptorProto::TYPE_BYTES:     return "bytes";
        case FieldDescriptorProto::TYPE_UINT32:    return "uint32";
        case FieldDescriptorProto::TYPE_ENUM:      return "enum";
        case FieldDescriptorProto::TYPE_SFIXED32:  return "sfixed32";
        case FieldDescriptorProto::TYPE_SFIXED64:  return "sfixed64";
        case FieldDescriptorProto::TYPE_SINT32:    return "sint32";
        case FieldDescriptorProto::TYPE_SINT64:    return "sint64";
    }

    return "???type";
}


// Return the C++ type corresponding to a fully qualified Protobuf message/enum type.
// Same-file package names are stripped, while lexical message nesting is preserved,
// so ".pkg.Outer.Inner" becomes "Outer::Inner" rather than context-dependent "Inner".
std::string cpp_qualified_type_str(str_view message_type)
{
    auto pkg_prefix_len = package_name_prefix.length();
    if (message_type.substr(0, pkg_prefix_len) == package_name_prefix) {
        message_type = message_type.substr(pkg_prefix_len);
    }

    return string_replace_all(message_type, PB_TYPE_DELIMITER, CPP_TYPE_DELIMITER);
}


// Return C++ type corresponding to the base type (without "repeated") of the Protobuf field
std::string base_cpp_type_as_str(const FieldDescriptorProto& field)
{
    // According to https://github.com/protocolbuffers/protobuf/blob/c05b320d9c18173bfce36c4bef22f9953d340ff9/src/google/protobuf/descriptor.h#L780
    switch(field.type)
    {
        case FieldDescriptorProto::TYPE_INT32:
        case FieldDescriptorProto::TYPE_SINT32:
        case FieldDescriptorProto::TYPE_SFIXED32: return "int32_t";

        case FieldDescriptorProto::TYPE_INT64:
        case FieldDescriptorProto::TYPE_SINT64:
        case FieldDescriptorProto::TYPE_SFIXED64: return "int64_t";

        case FieldDescriptorProto::TYPE_UINT32:
        case FieldDescriptorProto::TYPE_FIXED32:  return "uint32_t";

        case FieldDescriptorProto::TYPE_UINT64:
        case FieldDescriptorProto::TYPE_FIXED64:  return "uint64_t";

        case FieldDescriptorProto::TYPE_DOUBLE:   return "double";

        case FieldDescriptorProto::TYPE_FLOAT:    return "float";

        case FieldDescriptorProto::TYPE_BOOL:     return "bool";

        case FieldDescriptorProto::TYPE_STRING:
        case FieldDescriptorProto::TYPE_BYTES:    return option.cpp_string_type;

        case FieldDescriptorProto::TYPE_ENUM:
        case FieldDescriptorProto::TYPE_MESSAGE:  return cpp_qualified_type_str(field.type_name);

        case FieldDescriptorProto::TYPE_GROUP:    return "???group";
    }

    return "???type";
}


struct MapType
{
    const FieldDescriptorProto* key_field = nullptr;
    const FieldDescriptorProto* value_field = nullptr;
};

using MapTypeByName = std::map<std::string, MapType>;


// PB type suffix used by Encoder/Decoder methods (e.g. "fixed32" or "map_string_int32")
std::string protobuf_type_as_str(const FieldDescriptorProto& field, const MapType* map_type)
{
    if (map_type) {
        return myformat("map_{0}_{1}",
                        pbtype_name(*map_type->key_field),
                        pbtype_name(*map_type->value_field));
    }

    return std::string(pbtype_name(field));
}

// Return C++ type for the Protobuf field
std::string cpp_type_as_str(const FieldDescriptorProto& field, const MapType* map_type)
{
    auto basetype_str = base_cpp_type_as_str(field);

    if (map_type) {
        return myformat(option.cpp_map_type,
                        base_cpp_type_as_str(*map_type->key_field),
                        base_cpp_type_as_str(*map_type->value_field));
    }

    if (is_repeated(field)) {
        return myformat(option.cpp_repeated_type, basetype_str);
    } else {
        return basetype_str;
    }
}


// Generate an unscoped C++ enum while preserving descriptor order and values.
std::string generate_enum(const EnumDescriptorProto& enum_type,
                          const std::string& indent)
{
    std::string result = myformat("{0}enum {1}\n{0}{\n",
                                  indent, enum_type.name);

    for (std::size_t i = 0; i < enum_type.value.size(); ++i) {
        const auto& value = enum_type.value[i];
        result += myformat("{0}    {1} = {2}{3}\n",
                           indent, value.name, std::to_string(value.number),
                           i + 1 < enum_type.value.size() ? "," : "");
    }

    result += myformat("{0}};\n\n", indent);
    return result;
}


// Encoder code for a single field
std::string generate_field_encoder(const FieldDescriptorProto& field, const MapType* map_type)
{
    return myformat("    pb.put_{0}{1}({2}, {3});\n",
    /* 0 */ ! map_type && is_repeated(field)
                ? (write_as_packed(field)? "packed_" : "repeated_")
                : "",
    /* 1 */ protobuf_type_as_str(field, map_type),
    /* 2 */ std::to_string(field.number),
    /* 3 */ "x." + std::string(field.name));
}


// Decoder code for a single field
std::string generate_field_decoder(const FieldDescriptorProto& field, const MapType* map_type)
{
    return myformat("            case {0}: pb.get_{1}{2}(&{3}{4}); break;\n",
    /* 0 */ std::to_string(field.number),
    /* 1 */ ! map_type && is_repeated(field)? "repeated_" : "",
    /* 2 */ protobuf_type_as_str(field, map_type),
    /* 3 */ "x." + std::string(field.name),
    /* 4 */ hasfield_enabled(field)
                ? myformat(", &x.has_{0}", field.name)
                : "");
}


// Collect map types represented as the synthetic nested messages.
// The map entry itself is not emitted as a C++ struct; we keep only pointers to
// its key/value fields, indexed by the entry's absolute Protobuf type name.
MapTypeByName collect_map_types(const DescriptorProto& message_type,
                                const std::string& message_proto_name)
{
    MapTypeByName result;

    for (const auto& nested_msgtype: message_type.nested_type)
    {
        if (nested_msgtype.options.map_entry)
        {
            MapType map_type;

            for (const auto& field: nested_msgtype.field)
            {
                switch (field.number) {
                    case 1:  map_type.key_field   = &field;  break;
                    case 2:  map_type.value_field = &field;  break;
                }
            }

            auto qualified_name = message_proto_name + PB_TYPE_DELIMITER + std::string(nested_msgtype.name);

            if (! map_type.key_field || ! map_type.value_field) {
                throw std::runtime_error(
                    myformat("Malformed map entry {0}: fields 1 and 2 are required", qualified_name));
            }

            result[qualified_name] = map_type;
        }
    }

    return result;
}


// If field is a generated map field, return metadata for its synthetic map-entry
// message. Ordinary repeated message fields return nullptr. TYPE_GROUP remains
// unsupported as a map value even though message values are allowed.
const MapType* find_map_type(const FieldDescriptorProto& field,
                             const MapTypeByName& maptype_by_name,
                             str_view message_cpp_name)
{
    if (! is_repeated(field) || field.type != FieldDescriptorProto::TYPE_MESSAGE) {
        return nullptr;
    }

    auto field_type_name = std::string(field.type_name);
    auto map_it = maptype_by_name.find(field_type_name);
    if (map_it == maptype_by_name.end()) {
        return nullptr;
    }

    // These pointers refer to metadata owned by the map index and descriptor.
    const MapType* map_type = &map_it->second;
    const FieldDescriptorProto* value_field = map_type->value_field;
    auto value_type = value_field->type;

    if (value_type == FieldDescriptorProto::TYPE_GROUP)
    {
        throw std::runtime_error(
            myformat("Unsupported map value type '{0}' for field {1}.{2}",
                     pbtype_name(*value_field), message_cpp_name, field.name));
    }

    return map_type;
}


// Codegen-side description of one real Protobuf message.  It complements the
// descriptor with the names needed for C++ output and with resolved dependencies.
// `children` contains lexical nested messages but deliberately excludes synthetic
// map-entry messages.  Objects live inside the root `std::vector<MessageInfo>`;
// pointers stored in `dependencies` are filled only after that tree is complete.
struct MessageInfo
{
    const DescriptorProto* descriptor = nullptr;
    std::string simple_name;          // Inner
    std::string proto_name;           // .pkg.Outer.Inner
    std::string cpp_name;             // Outer::Inner
    std::string macro_name;           // Outer_Inner
    std::vector<MessageInfo> children;
    std::vector<MessageInfo*> dependencies;
};


// Absolute Protobuf type name -> MessageInfo.  This lets fields resolved by the
// parser/protoc be connected back to the message that Codegen will emit.
// In C++17 mode the key is a view into MessageInfo::proto_name or descriptor storage,
// so lookups avoid copying.
using MessageByProtoName = std::map<str_view, MessageInfo*>;


// Build the lexical MessageInfo tree and all four name forms in one recursive walk.
// Synthetic map entries stay in DescriptorProto::nested_type for map metadata,
// but are not added to the user-visible message tree.
MessageInfo make_message_info(const DescriptorProto& descriptor,
                              const std::string& parent_proto_name,
                              const std::string& parent_cpp_name,
                              const std::string& parent_macro_name)
{
    MessageInfo info;
    info.descriptor = &descriptor;
    info.simple_name = descriptor.name;
    info.proto_name = parent_proto_name.empty()
        ? package_name_prefix + info.simple_name
        : parent_proto_name + PB_TYPE_DELIMITER + info.simple_name;
    info.cpp_name = parent_cpp_name.empty()
        ? info.simple_name
        : parent_cpp_name + CPP_TYPE_DELIMITER + info.simple_name;
    info.macro_name = parent_macro_name.empty()
        ? info.simple_name
        : parent_macro_name + MACRO_TYPE_DELIMITER + info.simple_name;

    for (const auto& nested: descriptor.nested_type) {
        if (! nested.options.map_entry) {
            info.children.push_back(
                make_message_info(nested, info.proto_name, info.cpp_name, info.macro_name));
        }
    }

    return info;
}


// Add every real message in one lexical subtree to the absolute-name index.
void index_message_info(MessageInfo& info, MessageByProtoName& index)
{
    index[info.proto_name] = &info;
    for (auto& child: info.children) {
        index_message_info(child, index);
    }
}


// Flatten a MessageInfo subtree into pointers without changing source order.
// Several graph operations use this instead of duplicating recursive walks.
void collect_message_infos(MessageInfo& info, std::vector<MessageInfo*>& output)
{
    output.push_back(&info);
    for (auto& child: info.children) {
        collect_message_infos(child, output);
    }
}


// A nested C++ type is declared inside its ancestor.  If it stores that ancestor
// by value, no declaration order can make the C++ type complete, so this is a
// recursive value dependency even before general graph-cycle detection.
bool is_ancestor_message(const MessageInfo& ancestor, const MessageInfo& message)
{
    return message.proto_name != ancestor.proto_name &&
           starts_with(message.proto_name, ancestor.proto_name + PB_TYPE_DELIMITER);
}


// Keep dependency lists unique; one message may mention the same type in many fields.
void add_dependency(MessageInfo& source, MessageInfo* target)
{
    if (! target) return;
    for (auto* dependency: source.dependencies) {
        if (dependency == target) return;
    }
    source.dependencies.push_back(target);
}


// Resolve the message definition required by a field's user-defined type.
// Message fields need their target message, while nested enum fields need the
// message that owns the enum. Top-level enums have no message dependency.
MessageInfo* find_type_owner(const FieldDescriptorProto& field,
                             const MessageByProtoName& index)
{
    if (field.type == FieldDescriptorProto::TYPE_MESSAGE) {
        auto found = index.find(field.type_name);
        return found == index.end() ? nullptr : found->second;
    }

    if (field.type == FieldDescriptorProto::TYPE_ENUM) {
        const std::size_t separator = field.type_name.rfind(PB_TYPE_DELIMITER);
        if (separator == str_view::npos) return nullptr;
        const str_view owner_name = field.type_name.substr(0, separator);
        auto found = index.find(owner_name);
        return found == index.end() ? nullptr : found->second;
    }

    return nullptr;
}


// Resolve declaration dependencies between messages emitted from this file.
// Message fields depend directly on field.type_name; nested enum fields depend
// on the message that owns the enum. Maps use their synthetic entry's value
// field, so map<string, Child> depends on Child rather than hidden XxxEntry.
//
// External message/enum names are intentionally ignored here: source generation
// has already rejected unresolved imports, while descriptor-set mode preserves
// the existing behavior for types Codegen does not itself define.
void resolve_message_dependencies(MessageInfo& info,
                                  const MessageByProtoName& index)
{
    auto map_types = collect_map_types(*info.descriptor, info.proto_name);

    for (const auto& field: info.descriptor->field) {
        const MapType* map_type = find_map_type(field, map_types, info.cpp_name);
        const FieldDescriptorProto& dependency_field =
            map_type ? *map_type->value_field : field;
        MessageInfo* target = find_type_owner(dependency_field, index);
        if (! target) continue;

        if (dependency_field.type == FieldDescriptorProto::TYPE_MESSAGE &&
            is_ancestor_message(*target, info))
        {
            throw std::runtime_error(
                myformat("recursive message value dependency: {0} -> {1}",
                         info.cpp_name, target->cpp_name));
        }

        // An enum declared by this message or an ancestor is already visible
        // before this message's fields; it must not create a graph self-cycle.
        if (dependency_field.type == FieldDescriptorProto::TYPE_ENUM &&
            (target == &info || is_ancestor_message(*target, info)))
        {
            continue;
        }
        add_dependency(info, target);
    }

    for (auto& child: info.children) {
        resolve_message_dependencies(child, index);
    }
}


// DFS used for general self/mutual dependency detection. A back edge
// reconstructs the cycle in C++ names so the error explains why by-value
// generation is impossible.
void detect_dependency_cycles_visit(MessageInfo& info,
                                    std::map<MessageInfo*, GraphColor>& color,
                                    std::vector<MessageInfo*>& stack)
{
    color[&info] = GraphColor::OnStack;
    stack.push_back(&info);

    for (auto* dependency: info.dependencies) {
        if (color[dependency] == GraphColor::Unvisited) {
            detect_dependency_cycles_visit(*dependency, color, stack);
        } else if (color[dependency] == GraphColor::OnStack) {
            std::string path;
            std::size_t start = 0;
            while (start < stack.size() && stack[start] != dependency) ++start;
            for (std::size_t i = start; i < stack.size(); ++i) {
                if (! path.empty()) path += " -> ";
                path += stack[i]->cpp_name;
            }
            if (! path.empty()) path += " -> ";
            path += dependency->cpp_name;
            throw std::runtime_error("recursive message value dependency: " + path);
        }
    }

    stack.pop_back();
    color[&info] = GraphColor::Finished;
}


// Reject every by-value cycle before any generated text is returned to main().
void detect_dependency_cycles(std::vector<MessageInfo>& roots)
{
    std::map<MessageInfo*, GraphColor> color;
    std::vector<MessageInfo*> all_messages;
    for (auto& root: roots) collect_message_infos(root, all_messages);
    for (auto* message: all_messages) color[message] = GraphColor::Unvisited;

    std::vector<MessageInfo*> stack;
    for (auto* message: all_messages) {
        if (color[message] == GraphColor::Unvisited) {
            detect_dependency_cycles_visit(*message, color, stack);
        }
    }
}


// Return the top-level/sibling unit that lexically contains `message`.
// Topological ordering works on whole lexical subtrees because a nested C++
// struct cannot be moved outside its enclosing struct independently.
MessageInfo* containing_unit(const std::vector<MessageInfo*>& units,
                             const MessageInfo& message)
{
    for (auto* unit: units) {
        if (message.proto_name == unit->proto_name ||
            starts_with(message.proto_name, unit->proto_name + PB_TYPE_DELIMITER)) {
            return unit;
        }
    }
    return nullptr;
}


// Stable topological ordering for a set of sibling lexical subtrees.
// A dependency between any two messages inside different subtrees becomes a
// dependency between the corresponding roots.  Dependencies are visited in
// original source order so unrelated messages retain their previous order.
std::vector<MessageInfo*> stable_topological_order(const std::vector<MessageInfo*>& units)
{
    std::map<MessageInfo*, std::set<MessageInfo*> > dependencies;

    // Collapse field-level dependencies to the sibling/root granularity that
    // can actually be reordered in C++ source.
    for (auto* unit: units) {
        std::vector<MessageInfo*> subtree;
        collect_message_infos(*unit, subtree);
        for (auto* source: subtree) {
            for (auto* dependency: source->dependencies) {
                MessageInfo* target_unit = containing_unit(units, *dependency);
                if (target_unit && target_unit != unit) {
                    dependencies[unit].insert(target_unit);
                }
            }
        }
    }

    std::map<MessageInfo*, GraphColor> color;
    std::vector<MessageInfo*> result;
    std::vector<MessageInfo*> stack;
    for (auto* unit: units) color[unit] = GraphColor::Unvisited;

    struct Visitor {
        static void visit(MessageInfo* unit,
                          const std::vector<MessageInfo*>& units,
                          std::map<MessageInfo*, std::set<MessageInfo*> >& dependencies,
                          std::map<MessageInfo*, GraphColor>& color,
                          std::vector<MessageInfo*>& stack,
                          std::vector<MessageInfo*>& result)
        {
            color[unit] = GraphColor::OnStack;
            stack.push_back(unit);

            // Walk dependencies in source order to keep unrelated output stable.
            for (auto* candidate: units) {
                if (dependencies[unit].count(candidate) == 0) continue;
                if (color[candidate] == GraphColor::Unvisited) {
                    visit(candidate, units, dependencies, color, stack, result);
                } else if (color[candidate] == GraphColor::OnStack) {
                    // This is a cycle between lexical units (for example, two
                    // root structs whose nested messages depend on each other).
                    std::string path;
                    std::size_t start = 0;
                    while (start < stack.size() && stack[start] != candidate) ++start;
                    for (std::size_t i = start; i < stack.size(); ++i) {
                        if (! path.empty()) path += " -> ";
                        path += stack[i]->cpp_name;
                    }
                    if (! path.empty()) path += " -> ";
                    path += candidate->cpp_name;
                    throw std::runtime_error(
                        "recursive message value dependency: " + path);
                }
            }

            stack.pop_back();
            color[unit] = GraphColor::Finished;
            result.push_back(unit);  // dependencies were appended first
        }
    };

    for (auto* unit: units) {
        if (color[unit] == GraphColor::Unvisited) {
            Visitor::visit(unit, units, dependencies, color, stack, result);
        }
    }
    return result;
}


// Collect sibling/root messages and return them in dependency-safe declaration
// order, so every value-type dependency is emitted before its first use.
std::vector<MessageInfo*> dependency_safe_order(std::vector<MessageInfo>& messages)
{
    std::vector<MessageInfo*> units;
    for (auto& message: messages) units.push_back(&message);
    return stable_topological_order(units);
}


// Generate one message subtree in a single recursive walk.  The return value is
// the C++ struct text that must be embedded in the parent.  Encoder and decoder
// text is accumulated separately so all type definitions can be printed before
// any free codec functions, without making a second pass over the descriptor.
std::string generate_message(MessageInfo& info,
                             const std::string& indent,
                             std::string& encoders,
                             std::string& decoders)
{
    std::string nested_defs;
    // Enum declarations precede nested messages and fields that may use them.
    for (const auto& enum_type: info.descriptor->enum_type) {
        nested_defs += generate_enum(enum_type, indent + CPP_INDENT);
    }
    for (auto* child: dependency_safe_order(info.children)) {
        nested_defs += generate_message(*child, indent + CPP_INDENT, encoders, decoders);
    }

    std::string field_defs, has_field_defs, encoder, decoder, check_required_fields;
    auto map_types = collect_map_types(*info.descriptor, info.proto_name);

    for (const auto& field: info.descriptor->field)
    {
        auto map_type = find_map_type(field, map_types, info.cpp_name);

        auto cpptype_str = cpp_type_as_str(field, map_type);
        field_defs += myformat("{0}    {1} {2}{3};\n",
                               indent, cpptype_str, field.name,
                               default_value_str(field));

        if (hasfield_enabled(field)) {
            has_field_defs += myformat("{0}    bool has_{1} = false;\n",
                                       indent, field.name);
        }

        // Field codecs still use the same helpers as top-level messages; only
        // the enclosing type name and output section have changed.
        encoder += generate_field_encoder(field, map_type);
        decoder += generate_field_decoder(field, map_type);

        if ((field.label == FieldDescriptorProto::LABEL_REQUIRED) && ! option.no_required) {
            check_required_fields += myformat(
                CHECK_REQUIRED_FIELD_TEMPLATE, info.cpp_name, field.name);
        }
    }

    // Codec functions are emitted for every real message, including nested
    // ones. Their signatures use qualified C++ names such as Outer::Inner.
    if (! option.no_encoder) {
        encoders += myformat(ENCODER_TEMPLATE, info.cpp_name, info.macro_name, encoder);
    }
    if (! option.no_decoder) {
        decoders += myformat(DECODER_TEMPLATE, info.cpp_name, info.macro_name,
                             decoder, check_required_fields);
    }

    if (option.no_class) return "";
    return myformat(CLASS_TEMPLATE, indent, info.simple_name, nested_defs,
                    field_defs, has_field_defs, info.macro_name);
}


// Generate the body of one output header.  The dependency graph is built and
// validated before any text reaches main(), so recursive schemas fail without
// leaving a partial generated file.  Generation itself is one recursive pass:
// structs are returned in `class_defs`, while codecs are appended to their own
// sections and concatenated only after all message definitions are complete.
std::string generator(const FileDescriptorProto& file)
{
    // Set global vars
    current_file_is_proto3  =  file.has_syntax && (file.syntax == "proto3");
    package_name_prefix =
        file.package > ""
            ? PB_TYPE_DELIMITER + std::string(file.package) + PB_TYPE_DELIMITER
            : PB_TYPE_DELIMITER;

    // Build the lexical tree first. reserve() is important because the name
    // index will later store pointers into these root objects.
    std::vector<MessageInfo> roots;
    roots.reserve(file.message_type.size());
    for (const auto& message_type: file.message_type) {
        roots.push_back(make_message_info(message_type, "", "", ""));
    }

    // Resolve field type names to MessageInfo pointers only after the tree is
    // complete, then reject every dependency pattern impossible by C++ value.
    MessageByProtoName index;
    for (auto& root: roots) index_message_info(root, index);
    for (auto& root: roots) resolve_message_dependencies(root, index);
    detect_dependency_cycles(roots);

    std::string enum_defs, class_defs, encoders, decoders;
    // Top-level enums must be complete before any message field uses them.
    for (const auto& enum_type: file.enum_type) {
        enum_defs += generate_enum(enum_type, "");
    }
    // Top-level messages are ordered by the same dependency rule as nested siblings.
    for (auto* root: dependency_safe_order(roots)) {
        class_defs += generate_message(*root, "", encoders, decoders);
    }

    return enum_defs + class_defs + encoders + decoders;
}
